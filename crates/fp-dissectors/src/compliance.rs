use fp_core::{calculate_silence_intervals, LinkParams, RawBusEvent, RawFrame};
use serde::{Deserialize, Serialize};

use crate::modbus::{ModbusExceptionCode, ModbusPdu, ModbusRtuAdu};

/// Severity level of an audit finding
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
pub enum ViolationSeverity {
    Notice,
    Warning,
    Critical,
}

/// Structured diagnostic item within a compliance audit
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ComplianceIssue {
    pub severity: ViolationSeverity,
    pub rule_id: String,
    pub description: String,
    pub physical_hint: Option<String>,
}

/// Compliance report generated by inspecting live or recorded bus traffic
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct ComplianceReport {
    pub total_frames_analyzed: usize,
    pub crc_error_count: usize,
    pub timing_violation_count: usize,
    pub protocol_violation_count: usize,
    pub issues: Vec<ComplianceIssue>,
    pub link_health_score: f32,
}

impl ComplianceReport {
    pub fn new() -> Self {
        Self {
            link_health_score: 1.0,
            ..Default::default()
        }
    }

    pub fn add_issue(&mut self, issue: ComplianceIssue) {
        match issue.severity {
            ViolationSeverity::Critical => {
                self.link_health_score = (self.link_health_score - 0.2).max(0.0);
                self.protocol_violation_count += 1;
            }
            ViolationSeverity::Warning => {
                self.link_health_score = (self.link_health_score - 0.05).max(0.0);
                self.protocol_violation_count += 1;
            }
            ViolationSeverity::Notice => {}
        }
        self.issues.push(issue);
    }

    /// Audit a Modbus RTU frame using Zeek ICSNPP compliance algorithms
    pub fn audit_modbus_adu(&mut self, adu: &ModbusRtuAdu) {
        self.total_frames_analyzed += 1;

        match &adu.pdu {
            ModbusPdu::ReadHoldingRegistersQuery {
                start_addr,
                quantity,
            }
            | ModbusPdu::ReadInputRegistersQuery {
                start_addr,
                quantity,
            } => {
                // MODBUS-003: Max register quantity is 125 (0x7D)
                if *quantity == 0 || *quantity > 125 {
                    self.add_issue(ComplianceIssue {
                        severity: ViolationSeverity::Warning,
                        rule_id: "MODBUS-003-REG-QUANTITY".into(),
                        description: format!(
                            "Register query quantity {} is invalid (must be 1..125)",
                            quantity
                        ),
                        physical_hint: Some(
                            "Client requested excessive registers exceeding Modbus PDU limit."
                                .into(),
                        ),
                    });
                }

                // MODBUS-001: Register address overflow
                if (*start_addr as u32) + (*quantity as u32) > 65536 {
                    self.add_issue(ComplianceIssue {
                        severity: ViolationSeverity::Critical,
                        rule_id: "MODBUS-001-ADDR-OVERFLOW".into(),
                        description: format!(
                            "Start address {} + quantity {} exceeds 16-bit register space (65536)",
                            start_addr, quantity
                        ),
                        physical_hint: Some("Check PLC memory map; address out of bounds.".into()),
                    });
                }
            }

            ModbusPdu::ReadCoilsQuery {
                start_addr,
                quantity,
            }
            | ModbusPdu::ReadDiscreteInputsQuery {
                start_addr,
                quantity,
            } => {
                // MODBUS-003: Max coil quantity is 2000 (0x07D0)
                if *quantity == 0 || *quantity > 2000 {
                    self.add_issue(ComplianceIssue {
                        severity: ViolationSeverity::Warning,
                        rule_id: "MODBUS-003-COIL-QUANTITY".into(),
                        description: format!(
                            "Coil query quantity {} is invalid (must be 1..2000)",
                            quantity
                        ),
                        physical_hint: Some(
                            "Client requested excessive coils exceeding Modbus PDU limit.".into(),
                        ),
                    });
                }

                if (*start_addr as u32) + (*quantity as u32) > 65536 {
                    self.add_issue(ComplianceIssue {
                        severity: ViolationSeverity::Critical,
                        rule_id: "MODBUS-001-ADDR-OVERFLOW".into(),
                        description: format!(
                            "Start address {} + quantity {} exceeds 16-bit coil space",
                            start_addr, quantity
                        ),
                        physical_hint: Some("Check digital I/O table configuration.".into()),
                    });
                }
            }

            ModbusPdu::ReadResponse {
                function_code,
                byte_count,
                data,
            } => {
                // MODBUS-002: Byte count consistency
                if *byte_count as usize != data.len() {
                    self.add_issue(ComplianceIssue {
                        severity: ViolationSeverity::Critical,
                        rule_id: "MODBUS-002-BYTE-COUNT-MISMATCH".into(),
                        description: format!(
                            "FC 0x{:02X} byte count header ({}) does not match actual payload length ({})",
                            function_code, byte_count, data.len()
                        ),
                        physical_hint: Some("Serial frame truncated by timeout or hardware buffer overflow.".into()),
                    });
                }
            }

            ModbusPdu::Exception {
                original_fc,
                exception_code,
                raw_code,
            } => {
                let severity = match exception_code {
                    ModbusExceptionCode::ServerDeviceFailure
                    | ModbusExceptionCode::MemoryParityError => ViolationSeverity::Critical,
                    _ => ViolationSeverity::Warning,
                };
                self.add_issue(ComplianceIssue {
                    severity,
                    rule_id: "MODBUS-005-EXCEPTION-RESPONSE".into(),
                    description: format!(
                        "Slave 0x{:02X} returned Exception 0x{:02X} ({}) for FC 0x{:02X}",
                        adu.slave_id,
                        raw_code,
                        exception_code.name(),
                        original_fc
                    ),
                    physical_hint: Some(exception_code.description().to_string()),
                });
            }

            ModbusPdu::WriteSingleCoil { addr, value } if *value != 0x0000 && *value != 0xFF00 => {
                self.add_issue(ComplianceIssue {
                    severity: ViolationSeverity::Warning,
                    rule_id: "MODBUS-006-ILLEGAL-COIL-VALUE".into(),
                    description: format!(
                        "Write coil at {} has invalid value 0x{:04X} (must be 0x0000 or 0xFF00)",
                        addr, value
                    ),
                    physical_hint: Some(
                        "Modbus standard mandates only 0x0000 or 0xFF00 for single coil write."
                            .into(),
                    ),
                });
            }

            _ => {}
        }
    }

    /// Audit physical layer and timing compliance of a raw bus event
    pub fn audit_raw_event(&mut self, event: &RawBusEvent) {
        let baud = match &event.link_params {
            LinkParams::Serial(s) => s.baud_rate,
            _ => 9600,
        };
        self.audit_raw_event_with_baud(event, baud);
    }

    /// Audit physical layer and timing compliance of a raw bus event with explicit baud rate
    pub fn audit_raw_event_with_baud(&mut self, event: &RawBusEvent, baud_rate: u32) {
        self.total_frames_analyzed += 1;

        // 1. CAN physical/protocol error auditing
        if event.error_flags.can_crc_error {
            self.crc_error_count += 1;
            self.add_issue(ComplianceIssue {
                severity: ViolationSeverity::Critical,
                rule_id: "CAN-001-CRC-ERROR".into(),
                description: "CAN hardware CRC checksum error detected on interface".into(),
                physical_hint: Some(
                    "Electrical noise, improper cable termination, or transceiver distortion."
                        .into(),
                ),
            });
        }

        if event.error_flags.can_stuff_error {
            self.add_issue(ComplianceIssue {
                severity: ViolationSeverity::Critical,
                rule_id: "CAN-002-STUFF-ERROR".into(),
                description: "CAN bit stuffing rule violation (>5 identical consecutive bits)"
                    .into(),
                physical_hint: Some(
                    "Severe clock drift, bus reflection, or faulty physical transceiver.".into(),
                ),
            });
        }

        if event.error_flags.can_form_error || event.error_flags.can_bit_error {
            self.add_issue(ComplianceIssue {
                severity: ViolationSeverity::Warning,
                rule_id: "CAN-003-PHYSICAL-ERROR".into(),
                description: "CAN framing or bit monitoring error on transmission/reception".into(),
                physical_hint: Some(
                    "Differential signal integrity degraded or bus contention.".into(),
                ),
            });
        }

        if event.error_flags.can_ack_error {
            self.add_issue(ComplianceIssue {
                severity: ViolationSeverity::Warning,
                rule_id: "CAN-004-ACK-DELIMITER".into(),
                description: "CAN frame unacknowledged by any node on the bus".into(),
                physical_hint: Some(
                    "Isolated node, disconnected termination, or baud rate mismatch.".into(),
                ),
            });
        }

        if let RawFrame::Can(can_frame) = &event.payload {
            if can_frame.is_error {
                self.add_issue(ComplianceIssue {
                    severity: ViolationSeverity::Critical,
                    rule_id: "CAN-005-ERROR-FRAME".into(),
                    description: "Active/passive error frame received from CAN controller".into(),
                    physical_hint: Some(
                        "Node entered Error-Passive or Bus-Off state due to repeated faults."
                            .into(),
                    ),
                });
            }
        }

        // 2. Serial / UART physical error auditing
        if event.error_flags.uart_framing_error {
            self.timing_violation_count += 1;
            self.add_issue(ComplianceIssue {
                severity: ViolationSeverity::Critical,
                rule_id: "UART-001-FRAMING-ERROR".into(),
                description: "UART stop bit framing error detected".into(),
                physical_hint: Some(
                    "Baud rate mismatch or severe RS-485 slew rate / line capacitance distortion."
                        .into(),
                ),
            });
        }

        if event.error_flags.uart_parity_error {
            self.crc_error_count += 1;
            self.add_issue(ComplianceIssue {
                severity: ViolationSeverity::Critical,
                rule_id: "UART-002-PARITY-ERROR".into(),
                description: "UART parity check failed on received byte".into(),
                physical_hint: Some(
                    "Parity configuration (None/Even/Odd) mismatch or single-bit noise spike."
                        .into(),
                ),
            });
        }

        if event.error_flags.uart_overrun_error {
            self.add_issue(ComplianceIssue {
                severity: ViolationSeverity::Warning,
                rule_id: "UART-003-OVERRUN-ERROR".into(),
                description: "UART hardware FIFO overrun; byte dropped by receiver".into(),
                physical_hint: Some("Driver latency or interrupt starvation; reduce baud rate or optimize reader buffer.".into()),
            });
        }

        // 3. Serial inter-frame and inter-character timing verification (t1.5 and t3.5)
        if let RawFrame::Serial(chunk) = &event.payload {
            if let Some(gap_us) = chunk.inter_frame_gap_us {
                let silence = calculate_silence_intervals(baud_rate);

                // Modbus RTU timing rule: inter-character delay must not exceed t1.5.
                // A gap between t1.5 and t3.5 causes a receiver framing error because
                // the frame is discarded as incomplete without establishing the 3.5-char delimiter.
                if gap_us > silence.t1_5_us && gap_us < silence.t3_5_us {
                    self.timing_violation_count += 1;
                    self.add_issue(ComplianceIssue {
                        severity: ViolationSeverity::Warning,
                        rule_id: "MODBUS-004-TIMING-T1_5-VIOLATION".into(),
                        description: format!(
                            "Inter-character gap ({} us) exceeded t1.5 tolerance ({} us) without reaching t3.5 frame boundary ({} us)",
                            gap_us, silence.t1_5_us, silence.t3_5_us
                        ),
                        physical_hint: Some("Serial transmitter paused mid-frame or buffering delay on repeater/gateway.".into()),
                    });
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use fp_core::{BusErrorFlags, CanFrame, SerialParams, TimestampedChunk};

    #[test]
    fn test_modbus_register_overflow_compliance() {
        let mut report = ComplianceReport::new();
        let adu = ModbusRtuAdu {
            slave_id: 1,
            pdu: ModbusPdu::ReadHoldingRegistersQuery {
                start_addr: 65530,
                quantity: 10, // 65530 + 10 = 65540 > 65536
            },
            crc16: 0,
        };

        report.audit_modbus_adu(&adu);
        assert_eq!(report.issues.len(), 1);
        assert_eq!(report.issues[0].rule_id, "MODBUS-001-ADDR-OVERFLOW");
        assert_eq!(report.issues[0].severity, ViolationSeverity::Critical);
        assert!(report.link_health_score < 1.0);
    }

    #[test]
    fn test_modbus_exception_compliance() {
        let mut report = ComplianceReport::new();
        let adu = ModbusRtuAdu {
            slave_id: 1,
            pdu: ModbusPdu::Exception {
                original_fc: 0x03,
                exception_code: ModbusExceptionCode::ServerDeviceFailure,
                raw_code: 0x04,
            },
            crc16: 0,
        };

        report.audit_modbus_adu(&adu);
        assert_eq!(report.issues.len(), 1);
        assert_eq!(report.issues[0].severity, ViolationSeverity::Critical);
    }

    #[test]
    fn test_compliance_audit_raw_event_timing_violation() {
        let mut report = ComplianceReport::new();

        // 9600 baud: char time ~1146 us -> t1.5 ~1719 us, t3.5 ~4010 us
        let chunk = TimestampedChunk::new(vec![0x01, 0x03, 0x00], Some(2500));
        let event = RawBusEvent::new_serial_rx(
            "ttyUSB0",
            1_000_000,
            LinkParams::Serial(SerialParams {
                baud_rate: 9600,
                ..Default::default()
            }),
            chunk,
        );

        report.audit_raw_event(&event);
        assert_eq!(report.total_frames_analyzed, 1);
        assert_eq!(report.timing_violation_count, 1);
        assert_eq!(report.issues.len(), 1);
        assert_eq!(report.issues[0].rule_id, "MODBUS-004-TIMING-T1_5-VIOLATION");
        assert!(report.link_health_score < 1.0);
    }

    #[test]
    fn test_compliance_audit_raw_event_can_crc_and_error_flags() {
        let mut report = ComplianceReport::new();

        let mut error_frame = CanFrame::new_standard(0x000, &[]);
        error_frame.is_error = true;

        let mut event =
            RawBusEvent::new_can_rx("can0", 1_000_000, LinkParams::default(), error_frame);
        event.error_flags = BusErrorFlags {
            can_crc_error: true,
            ..Default::default()
        };

        report.audit_raw_event(&event);
        assert_eq!(report.total_frames_analyzed, 1);
        assert_eq!(report.crc_error_count, 1);
        assert_eq!(report.protocol_violation_count, 2); // 1 for CRC critical + 1 for CAN error frame critical
        assert_eq!(report.issues.len(), 2);
    }
}
