use serde::{Deserialize, Serialize};

use crate::modbus::{ModbusExceptionCode, ModbusPdu, ModbusRtuAdu};

/// Severity level of an audit finding
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
pub enum ViolationSeverity {
    Notice,
    Warning,
    Critical,
}

/// Structured diagnostic item within a compliance audit
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ComplianceIssue {
    pub severity: ViolationSeverity,
    pub rule_id: String,
    pub description: String,
    pub physical_hint: Option<String>,
}

/// Compliance report generated by inspecting live or recorded bus traffic
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct ComplianceReport {
    pub total_frames_analyzed: usize,
    pub crc_error_count: usize,
    pub timing_violation_count: usize,
    pub protocol_violation_count: usize,
    pub issues: Vec<ComplianceIssue>,
    pub link_health_score: f32,
}

impl ComplianceReport {
    pub fn new() -> Self {
        Self {
            link_health_score: 1.0,
            ..Default::default()
        }
    }

    pub fn add_issue(&mut self, issue: ComplianceIssue) {
        match issue.severity {
            ViolationSeverity::Critical => {
                self.link_health_score = (self.link_health_score - 0.2).max(0.0);
                self.protocol_violation_count += 1;
            }
            ViolationSeverity::Warning => {
                self.link_health_score = (self.link_health_score - 0.05).max(0.0);
                self.protocol_violation_count += 1;
            }
            ViolationSeverity::Notice => {}
        }
        self.issues.push(issue);
    }

    /// Audit a Modbus RTU frame using Zeek ICSNPP compliance algorithms
    pub fn audit_modbus_adu(&mut self, adu: &ModbusRtuAdu) {
        self.total_frames_analyzed += 1;

        match &adu.pdu {
            ModbusPdu::ReadHoldingRegistersQuery { start_addr, quantity }
            | ModbusPdu::ReadInputRegistersQuery { start_addr, quantity } => {
                // MODBUS-003: Max register quantity is 125 (0x7D)
                if *quantity == 0 || *quantity > 125 {
                    self.add_issue(ComplianceIssue {
                        severity: ViolationSeverity::Warning,
                        rule_id: "MODBUS-003-REG-QUANTITY".into(),
                        description: format!(
                            "Register query quantity {} is invalid (must be 1..125)",
                            quantity
                        ),
                        physical_hint: Some("Client requested excessive registers exceeding Modbus PDU limit.".into()),
                    });
                }

                // MODBUS-001: Register address overflow
                if (*start_addr as u32) + (*quantity as u32) > 65536 {
                    self.add_issue(ComplianceIssue {
                        severity: ViolationSeverity::Critical,
                        rule_id: "MODBUS-001-ADDR-OVERFLOW".into(),
                        description: format!(
                            "Start address {} + quantity {} exceeds 16-bit register space (65536)",
                            start_addr, quantity
                        ),
                        physical_hint: Some("Check PLC memory map; address out of bounds.".into()),
                    });
                }
            }

            ModbusPdu::ReadCoilsQuery { start_addr, quantity }
            | ModbusPdu::ReadDiscreteInputsQuery { start_addr, quantity } => {
                // MODBUS-003: Max coil quantity is 2000 (0x07D0)
                if *quantity == 0 || *quantity > 2000 {
                    self.add_issue(ComplianceIssue {
                        severity: ViolationSeverity::Warning,
                        rule_id: "MODBUS-003-COIL-QUANTITY".into(),
                        description: format!(
                            "Coil query quantity {} is invalid (must be 1..2000)",
                            quantity
                        ),
                        physical_hint: Some("Client requested excessive coils exceeding Modbus PDU limit.".into()),
                    });
                }

                if (*start_addr as u32) + (*quantity as u32) > 65536 {
                    self.add_issue(ComplianceIssue {
                        severity: ViolationSeverity::Critical,
                        rule_id: "MODBUS-001-ADDR-OVERFLOW".into(),
                        description: format!(
                            "Start address {} + quantity {} exceeds 16-bit coil space",
                            start_addr, quantity
                        ),
                        physical_hint: Some("Check digital I/O table configuration.".into()),
                    });
                }
            }

            ModbusPdu::ReadResponse { function_code, byte_count, data } => {
                // MODBUS-002: Byte count consistency
                if *byte_count as usize != data.len() {
                    self.add_issue(ComplianceIssue {
                        severity: ViolationSeverity::Critical,
                        rule_id: "MODBUS-002-BYTE-COUNT-MISMATCH".into(),
                        description: format!(
                            "FC 0x{:02X} byte count header ({}) does not match actual payload length ({})",
                            function_code, byte_count, data.len()
                        ),
                        physical_hint: Some("Serial frame truncated by timeout or hardware buffer overflow.".into()),
                    });
                }
            }

            ModbusPdu::Exception { original_fc, exception_code, raw_code } => {
                let severity = match exception_code {
                    ModbusExceptionCode::ServerDeviceFailure | ModbusExceptionCode::MemoryParityError => {
                        ViolationSeverity::Critical
                    }
                    _ => ViolationSeverity::Warning,
                };
                self.add_issue(ComplianceIssue {
                    severity,
                    rule_id: "MODBUS-005-EXCEPTION-RESPONSE".into(),
                    description: format!(
                        "Slave 0x{:02X} returned Exception 0x{:02X} ({}) for FC 0x{:02X}",
                        adu.slave_id, raw_code, exception_code.name(), original_fc
                    ),
                    physical_hint: Some(exception_code.description().to_string()),
                });
            }

            ModbusPdu::WriteSingleCoil { addr, value }
                if *value != 0x0000 && *value != 0xFF00 =>
            {
                self.add_issue(ComplianceIssue {
                    severity: ViolationSeverity::Warning,
                    rule_id: "MODBUS-006-ILLEGAL-COIL-VALUE".into(),
                    description: format!(
                        "Write coil at {} has invalid value 0x{:04X} (must be 0x0000 or 0xFF00)",
                        addr, value
                    ),
                    physical_hint: Some("Modbus standard mandates only 0x0000 or 0xFF00 for single coil write.".into()),
                });
            }

            _ => {}
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_modbus_register_overflow_compliance() {
        let mut report = ComplianceReport::new();
        let adu = ModbusRtuAdu {
            slave_id: 1,
            pdu: ModbusPdu::ReadHoldingRegistersQuery {
                start_addr: 65530,
                quantity: 10, // 65530 + 10 = 65540 > 65536
            },
            crc16: 0,
        };

        report.audit_modbus_adu(&adu);
        assert_eq!(report.issues.len(), 1);
        assert_eq!(report.issues[0].rule_id, "MODBUS-001-ADDR-OVERFLOW");
        assert_eq!(report.issues[0].severity, ViolationSeverity::Critical);
        assert!(report.link_health_score < 1.0);
    }

    #[test]
    fn test_modbus_exception_compliance() {
        let mut report = ComplianceReport::new();
        let adu = ModbusRtuAdu {
            slave_id: 1,
            pdu: ModbusPdu::Exception {
                original_fc: 0x03,
                exception_code: ModbusExceptionCode::ServerDeviceFailure,
                raw_code: 0x04,
            },
            crc16: 0,
        };

        report.audit_modbus_adu(&adu);
        assert_eq!(report.issues.len(), 1);
        assert_eq!(report.issues[0].severity, ViolationSeverity::Critical);
    }
}
